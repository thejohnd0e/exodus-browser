import type { Fingerprint } from './fingerprint';
import type {AppSettings} from './settings';
import type {UpdateState} from './update';
import type {AgentApiStatus, AgentCredentialGrantInput} from './agent-api';
export type ProxyInput = { kind: 'http'|'https'|'socks5'; host: string; port: number; username?: string; password?: string };
export type ProxyPublic = Omit<ProxyInput,'password'> & {hasPassword:boolean;requiresPassword?:boolean};
export type SavedProxyInput = ProxyInput & {name:string};
export type SavedProxy = ProxyPublic & {id:string;name:string;createdAt:string;updatedAt:string;profileIds:string[]};
export type ProfileInput = {name:string;note:string;startUrls:string[];languages:string[];proxyId:string|null;fingerprint?:Fingerprint;restoreLastSession?:boolean;fingerprintSeed?:number;extensionIds?:string[]};
export type Profile = Omit<ProfileInput,'fingerprint'|'restoreLastSession'|'fingerprintSeed'|'extensionIds'> & {fingerprint:Fingerprint;restoreLastSession:boolean;fingerprintSeed:number;extensionIds:string[];id:string;proxy:SavedProxy|null;createdAt:string;updatedAt:string};
export type LaunchInput = Omit<ProfileInput,'proxyId'|'fingerprint'|'restoreLastSession'|'fingerprintSeed'|'extensionIds'> & {fingerprint:Fingerprint;restoreLastSession:boolean;fingerprintSeed:number;extensionIds:string[];proxy:ProxyInput|null;proxyVersion:string|null};
export type ProfileState = 'stopped'|'starting'|'running'|'stopping'|'error'|'blocked';
export type LaunchWarning = {code:'TIMEZONE_UNRESOLVED'};
/** Targets of the current or last run whose fingerprint could not be installed (DECISIONS #80). */
export type ProtectionIssues = {closed:number;unprotected:number};
export type CookieOperationResult = {count:number;fileName:string};
export type CookieFormat = 'json'|'netscape';
export type Result<T> = {ok:true;value:T}|{ok:false;error:{code:string;message:string}};
export type EngineInstallProgress = {stage:'download'|'extract'|'verify';received?:number;total?:number|null};
export type EngineStatus = {state:'missing'|'ready'|'unsupported'|'installing';version?:string;source?:'downloaded'|'external'|'branded';progress?:EngineInstallProgress;compatibility?:'supported'|'older'|'newer'|'unknown';supportedMajors?:{min:number;max:number};latestVersion?:string;latestCompatibility?:'supported'|'older'|'newer'|'unknown';hostGpuVendors?:string[];hostGpuModels?:string[]};
export type ExtensionSource = 'folder' | 'zip' | 'store';
export type ExtensionEntry = {id: string; name: string; version: string; source: ExtensionSource; storeId?: string; addedAt: string; updatedAt: string};
export type ExtensionResult = Result<ExtensionEntry | null>;
export interface ProfileApi {
  list():Promise<Result<Profile[]>>;
  create(input:ProfileInput):Promise<Result<Profile>>;
  update(id:string,input:ProfileInput):Promise<Result<Profile>>;
  remove(id:string):Promise<Result<void>>;
  start(id:string):Promise<Result<void>>;
  stop(id:string):Promise<Result<void>>;
  states():Promise<Result<Record<string,ProfileState>>>;
  warnings():Promise<Result<Record<string,LaunchWarning>>>;
  protectionIssues():Promise<Result<Record<string,ProtectionIssues>>>;
  engineStatus():Promise<Result<EngineStatus>>;
  installEngine():Promise<Result<void>>;
  linkEngine():Promise<Result<void>>;
  backup(id:string):Promise<Result<void>>;
  restore():Promise<Result<Profile|null>>;
  exportProfile(id:string):Promise<Result<{fileName:string}|null>>;
  importProfile():Promise<Result<Profile|null>>;
  checkProxy(id:string):Promise<Result<{ip:string;countryCode:string|null;service:string}|null>>;
  listProxies():Promise<Result<SavedProxy[]>>;
  createProxy(input:SavedProxyInput):Promise<Result<SavedProxy>>;
  updateProxy(id:string,input:SavedProxyInput):Promise<Result<SavedProxy>>;
  removeProxy(id:string):Promise<Result<void>>;
  checkSavedProxy(id:string):Promise<Result<{ip:string;countryCode:string|null;service:string}>>;
  importCookies(id:string):Promise<Result<CookieOperationResult|null>>;
  exportCookies(id:string,format:CookieFormat):Promise<Result<CookieOperationResult|null>>;
  clearCookies(id:string):Promise<Result<{cleared:true}|null>>;
  getSettings():Promise<Result<AppSettings>>;
  updateSettings(input:AppSettings):Promise<Result<AppSettings>>;
  agentApiStatus():Promise<Result<AgentApiStatus>>;
  setAgentApiEnabled(enabled:boolean):Promise<Result<AgentApiStatus>>;
  createAgentCredential(label:string):Promise<Result<{id:string;token:string}>>;
  revokeAgentCredential(id:string):Promise<Result<void>>;
  grantAgentCredential(input:AgentCredentialGrantInput):Promise<Result<void>>;
  revokeAgentGrant(input:AgentCredentialGrantInput):Promise<Result<void>>;
  copyText?(text:string):Promise<Result<void>>;
  runningProxyVersions():Promise<Result<Record<string,string|null>>>;
  listExtensions():Promise<Result<ExtensionEntry[]>>;
  addExtensionFolder():Promise<ExtensionResult>;
  addExtensionZip():Promise<ExtensionResult>;
  addExtensionFromStore(link:string):Promise<ExtensionResult>;
  updateExtension(id:string):Promise<ExtensionResult>;
  removeExtension(id:string):Promise<Result<void>>;
  getUpdateState():Promise<Result<UpdateState>>;
  checkForUpdate():Promise<Result<UpdateState>>;
  downloadUpdate():Promise<Result<UpdateState>>;
  cancelUpdate():Promise<Result<void>>;
  installUpdate():Promise<Result<void>>;
  onUpdateState(callback:(state:UpdateState)=>void):()=>void;
  onCloseRequested(callback:()=>void):()=>void;
  confirmClose(shouldClose:boolean):Promise<boolean>;
}
